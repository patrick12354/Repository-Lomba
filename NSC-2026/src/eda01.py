import pandas as pd, numpy as np
pd.set_option('display.width',200); pd.set_option('display.max_columns',60)
D='Dataset/'
tr=pd.read_csv(D+'train.csv',parse_dates=['datetime'])
te=pd.read_csv(D+'test.csv',parse_dates=['datetime'])
ss=pd.read_csv(D+'sample_submission.csv',parse_dates=['datetime'])
print('train',tr.shape,'test',te.shape,'sub',ss.shape)
print('train range',tr.datetime.min(),'->',tr.datetime.max())
print('test  range',te.datetime.min(),'->',te.datetime.max())
print('sub==test datetime:', (ss.datetime.values==te.datetime.values).all())
print('train dup dt',tr.datetime.duplicated().sum(),'test dup',te.datetime.duplicated().sum())
print('train sorted',tr.datetime.is_monotonic_increasing,'test sorted',te.datetime.is_monotonic_increasing)
d=tr.datetime.diff().dt.total_seconds().div(60).value_counts()
print('\ntrain gaps(min):'); print(d.head(10))
d2=te.datetime.diff().dt.total_seconds().div(60).value_counts()
print('test gaps(min):'); print(d2.head(10))
# full grid check
full=pd.date_range(tr.datetime.min(),te.datetime.max(),freq='30min')
print('\nfull 30min grid len',len(full),'| train+test',len(tr)+len(te),'| missing slots',len(full)-len(tr)-len(te))
print('\n--- MISSINGNESS (train) ---')
m=tr.isna().mean().sort_values(ascending=False)
print((m*100).round(2))
print('\n--- MISSINGNESS (test) ---')
m2=te.isna().mean().sort_values(ascending=False)
print((m2*100).round(2))
print('\n--- TARGET describe ---')
print(tr.air_humidity.describe())
print('\n--- numeric describe (train) ---')
print(tr.describe().T[['count','mean','std','min','25%','50%','75%','max']].round(2))
print('\n--- numeric describe (test) ---')
print(te.describe().T[['count','mean','std','min','25%','50%','75%','max']].round(2))
